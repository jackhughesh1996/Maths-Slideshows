/**
 * @file generate-lesson-catalog.js
 * Build-time script to generate a lightweight lesson metadata catalogue.
 * Reads lessonManifest, dynamically imports each lesson module, validates it,
 * extracts key metadata (excluding slides), and outputs src/generated/lesson-catalog.js.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { lessonManifest } from '../src/lessons/manifest.js';
import { validateLesson } from '../src/slideshow/validator.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const manifestDir = path.resolve(rootDir, 'src', 'lessons');
const outputDir = path.resolve(rootDir, 'src', 'generated');
const outputFile = path.join(outputDir, 'lesson-catalog.js');

export async function generateLessonCatalog() {
  console.log('\n======================================================');
  console.log('   Lesson Catalogue Generator');
  console.log('======================================================\n');

  if (!Array.isArray(lessonManifest) || lessonManifest.length === 0) {
    throw new Error('[Catalog Generator] lessonManifest is missing or empty.');
  }

  const seenIds = new Set();
  const catalog = [];

  for (const entry of lessonManifest) {
    if (!entry || !entry.id || !entry.path) {
      throw new Error(`[Catalog Generator] Invalid manifest entry: ${JSON.stringify(entry)}`);
    }

    if (seenIds.has(entry.id)) {
      throw new Error(`[Catalog Generator] Duplicate lesson ID detected in manifest: "${entry.id}".`);
    }
    seenIds.add(entry.id);

    // Resolve path relative to manifest file directory
    const lessonFilePath = path.resolve(manifestDir, entry.path);
    if (!fs.existsSync(lessonFilePath)) {
      throw new Error(`[Catalog Generator] Lesson file not found at: ${lessonFilePath}`);
    }

    // Dynamically import lesson module
    const fileUrl = pathToFileURL(lessonFilePath).href;
    const imported = await import(fileUrl);
    const lesson = imported.default || imported;

    if (!lesson || typeof lesson !== 'object') {
      throw new Error(`[Catalog Generator] Lesson module at "${entry.path}" did not export an object.`);
    }

    // Verify ID matches manifest
    if (lesson.id !== entry.id) {
      throw new Error(
        `[Catalog Generator] Lesson ID mismatch: manifest specified "${entry.id}", but module defines "${lesson.id}".`
      );
    }

    // Validate lesson using existing validator
    const validation = validateLesson(lesson, { silent: false });
    if (!validation.valid) {
      throw new Error(
        `[Catalog Generator] Validation failed for lesson "${entry.id}":\n` +
        validation.errors.map((e) => `  - ${e}`).join('\n')
      );
    }

    const metadata = {
      id: lesson.id,
      title: lesson.title,
      subject: lesson.subject,
      yearLevel: lesson.yearLevel,
      unit: lesson.unit,
      folder: lesson.folder,
      chapter: lesson.chapter,
      topics: Array.isArray(lesson.topics) ? [...lesson.topics] : [],
      ...(lesson.order !== undefined ? { order: lesson.order } : {}),
      slideCount: Array.isArray(lesson.slides) ? lesson.slides.length : 0
    };

    catalog.push(metadata);
    console.log(`  ✓ [${metadata.id}] ${metadata.title} (${metadata.slideCount} slides)`);
  }

  // Ensure output directory exists
  fs.mkdirSync(outputDir, { recursive: true });

  const catalogJson = JSON.stringify(catalog, null, 2);
  const fileContent = `/**
 * @file lesson-catalog.js
 * Automatically generated by scripts/generate-lesson-catalog.js.
 * Do not edit directly.
 */

export const lessonCatalog = ${catalogJson};

export default lessonCatalog;
`;

  fs.writeFileSync(outputFile, fileContent, 'utf-8');
  console.log(`\nSuccessfully generated catalogue with ${catalog.length} lessons at src/generated/lesson-catalog.js\n`);

  return catalog;
}

// Execute directly if run as main script
const isDirectRun = process.argv[1] && path.resolve(process.argv[1]) === path.resolve(__filename);
if (isDirectRun) {
  generateLessonCatalog().catch((err) => {
    console.error('[Catalog Generator] Fatal error:', err.message);
    process.exit(1);
  });
}
