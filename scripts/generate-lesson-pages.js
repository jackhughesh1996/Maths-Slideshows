/**
 * @file generate-lesson-pages.js
 * Build-time script to generate static HTML entry pages for each lesson in lessons/<id>/index.html.
 * Each page mounts the shared /src/lesson-entry.js module.
 * Safely removes obsolete generated lesson pages when lessons are removed or renamed.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { lessonManifest } from '../src/lessons/manifest.js';
import { lessonCatalog } from '../src/generated/lesson-catalog.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const targetLessonsDir = path.resolve(rootDir, 'lessons');

const GENERATOR_IDENTIFIER_COMMENT =
  '<!-- Automatically generated by scripts/generate-lesson-pages.js. Do not edit directly. -->';

/**
 * Escape HTML special characters for attributes and text content.
 * @param {string} str
 * @returns {string}
 */
function escapeHtml(str) {
  if (!str) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/**
 * Validate that an ID is safe to use as a directory name without traversal risks.
 * @param {string} id
 * @returns {string}
 */
function validateSafeDirectoryId(id) {
  if (!id || typeof id !== 'string') {
    throw new Error(`[Page Generator] Lesson ID is missing or invalid: ${id}`);
  }
  const trimmed = id.trim();
  // Safe alphanumeric badge, allowing dashes/underscores, no slashes or dots
  if (!/^[A-Za-z0-9_-]+$/.test(trimmed)) {
    throw new Error(
      `[Page Generator] Unsafe or invalid lesson ID "${id}". ID must contain only alphanumeric characters, underscores, or hyphens.`
    );
  }
  return trimmed;
}

/**
 * Generate HTML markup for a lesson page.
 * @param {Object} metadata
 * @returns {string}
 */
function createLessonHtml(metadata) {
  const safeId = escapeHtml(metadata.id);
  const safeTitle = escapeHtml(metadata.title || metadata.id);
  const pageTitle = `${safeId}: ${safeTitle} - Year 7 Mathematics`;
  const description = metadata.topics && metadata.topics.length > 0
    ? `Interactive classroom slideshow for Year 7 Mathematics on ${safeTitle} (${metadata.topics.join(', ')}).`
    : `Interactive classroom slideshow for Year 7 Mathematics on ${safeTitle}.`;

  return `<!doctype html>
${GENERATOR_IDENTIFIER_COMMENT}
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>${pageTitle}</title>
    <meta name="description" content="${escapeHtml(description)}" />
  </head>
  <body>
    <div id="app" data-lesson-id="${safeId}"></div>
    <script type="module" src="/src/lesson-entry.js"></script>
  </body>
</html>
`;
}

/**
 * Clean up obsolete generated lesson pages.
 * Safely removes only index.html files that contain the generator comment
 * within directories not registered in lessonManifest.
 * Removes parent directory only if it becomes empty.
 * @param {Set<string>} registeredSafeIds
 * @returns {Array<string>} List of removed file paths relative to rootDir
 */
function cleanupObsoleteLessonPages(registeredSafeIds) {
  if (!fs.existsSync(targetLessonsDir)) {
    return [];
  }

  const removedFiles = [];
  const entries = fs.readdirSync(targetLessonsDir, { withFileTypes: true });

  for (const entry of entries) {
    if (!entry.isDirectory()) {
      continue;
    }

    const dirName = entry.name;
    // If registered, do not clean up
    if (registeredSafeIds.has(dirName)) {
      continue;
    }

    const subDirPath = path.resolve(targetLessonsDir, dirName);
    const indexPath = path.resolve(subDirPath, 'index.html');

    // Only inspect if index.html exists
    if (!fs.existsSync(indexPath)) {
      continue;
    }

    try {
      const content = fs.readFileSync(indexPath, 'utf-8');
      // Must contain exact generator identification comment
      if (!content.includes(GENERATOR_IDENTIFIER_COMMENT)) {
        console.log(`  ℹ Preserving unregistered custom HTML at ${path.relative(rootDir, indexPath)}`);
        continue;
      }

      // Delete only the generated index.html file
      fs.unlinkSync(indexPath);
      const relIndexPath = path.relative(rootDir, indexPath);
      console.log(`  ✓ Removed obsolete generated page: ${relIndexPath}`);
      removedFiles.push(relIndexPath);

      // Check if directory is now empty
      const remaining = fs.readdirSync(subDirPath);
      if (remaining.length === 0) {
        fs.rmdirSync(subDirPath);
        console.log(`  ✓ Removed empty directory: ${path.relative(rootDir, subDirPath)}`);
      } else {
        console.log(`  ℹ Preserved directory with remaining files: ${path.relative(rootDir, subDirPath)}`);
      }
    } catch (err) {
      console.warn(`  ⚠ Warning: Could not process directory ${dirName} during cleanup:`, err.message);
    }
  }

  return removedFiles;
}

export function generateLessonPages() {
  console.log('\n======================================================');
  console.log('   Static Lesson HTML Page Generator');
  console.log('======================================================\n');

  if (!Array.isArray(lessonManifest) || lessonManifest.length === 0) {
    throw new Error('[Page Generator] lessonManifest is missing or empty.');
  }

  // Create lookup dictionary for catalog metadata
  const catalogMap = new Map();
  if (Array.isArray(lessonCatalog)) {
    for (const item of lessonCatalog) {
      if (item && item.id) {
        catalogMap.set(String(item.id).trim().toUpperCase(), item);
      }
    }
  }

  fs.mkdirSync(targetLessonsDir, { recursive: true });

  const registeredSafeIds = new Set();
  const generatedPages = [];

  for (const manifestEntry of lessonManifest) {
    const rawId = manifestEntry.id;
    const safeId = validateSafeDirectoryId(rawId);
    registeredSafeIds.add(safeId);

    const catalogEntry = catalogMap.get(safeId.toUpperCase()) || {};
    const metadata = {
      ...catalogEntry,
      id: rawId,
      title: catalogEntry.title || rawId,
    };

    const lessonDir = path.resolve(targetLessonsDir, safeId);

    // Prevent directory traversal verification
    const relativeToLessons = path.relative(targetLessonsDir, lessonDir);
    if (relativeToLessons.startsWith('..') || path.isAbsolute(relativeToLessons)) {
      throw new Error(`[Page Generator] Path traversal attempt detected for lesson ID: "${rawId}"`);
    }

    fs.mkdirSync(lessonDir, { recursive: true });

    const htmlPath = path.resolve(lessonDir, 'index.html');

    // Refuse to overwrite manually authored index.html
    if (fs.existsSync(htmlPath)) {
      const existingContent = fs.readFileSync(htmlPath, 'utf-8');
      if (!existingContent.includes(GENERATOR_IDENTIFIER_COMMENT)) {
        throw new Error(
          `[Page Generator] Conflicting manually authored file detected at "${path.relative(rootDir, htmlPath)}". File does not contain generator identification comment.`
        );
      }
    }

    const htmlContent = createLessonHtml(metadata);
    fs.writeFileSync(htmlPath, htmlContent, 'utf-8');

    generatedPages.push({
      id: rawId,
      path: htmlPath,
      relPath: path.relative(rootDir, htmlPath),
    });

    console.log(`  ✓ Generated ${path.relative(rootDir, htmlPath)} (Lesson ${rawId})`);
  }

  // Clean up any obsolete generated pages
  const removedPages = cleanupObsoleteLessonPages(registeredSafeIds);

  console.log(`\nSuccessfully generated ${generatedPages.length} lesson HTML pages.`);
  if (removedPages.length > 0) {
    console.log(`Cleaned up ${removedPages.length} obsolete generated page(s).\n`);
  } else {
    console.log('');
  }

  return generatedPages;
}

// Execute directly if run as main script
const isDirectRun = process.argv[1] && path.resolve(process.argv[1]) === path.resolve(__filename);
if (isDirectRun) {
  try {
    generateLessonPages();
  } catch (err) {
    console.error('[Page Generator] Fatal error:', err.message);
    process.exit(1);
  }
}
